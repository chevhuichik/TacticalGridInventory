local i, PER = 0, 30
local extra = {}
local function itemIcons()
    local p = getSpecificPlayer(0)
    if not p then return end
    local seen = {}
    local function walk(inv, depth)
        if not inv or depth > 3 then return end
        local items = inv:getItems()
        for k = 0, items:size() - 1 do
            local it = items:get(k)
            local t = it and it:getTex()
            if t and not seen[t] then seen[t] = true; extra[#extra + 1] = t end
            if it and it.getInventory and instanceof(it, "InventoryContainer") then walk(it:getInventory(), depth + 1) end
        end
    end
    walk(p:getInventory(), 0)
end

local Warm = ISUIElement:derive("TGITextureWarm")
function Warm:render()
    local n = 0
    while n < 40 do
        self.j = (self.j or 0) + 1
        local t = self.list[self.j]
        if not t then self:removeFromUIManager(); return end
        self:drawTextureScaled(t, 0, 0, 1, 1, 0.01, 1, 1, 1)
        n = n + 1
    end
end

local function step()
    for _ = 1, PER do
        i = i + 1
        local p = LIST[i]
        if not p then
            Events.OnTick.Remove(step)
            pcall(itemIcons)
            local all = {}
            for _, path in ipairs(LIST) do local t = getTexture(path); if t then all[#all + 1] = t end end
            for _, t in ipairs(extra) do all[#all + 1] = t end
            local w = Warm:new(0, 0, 1, 1)
            w.list = all
            w:initialise()
            w:addToUIManager()
            pcall(function() w.javaObject:setConsumeMouseEvents(false) end)
            return
        end
        getTexture(p)
    end
end
Events.OnGameStart.Add(function() i = 0; Events.OnTick.Add(step) end)
